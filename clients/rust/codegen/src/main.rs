//! OpenAPI -> Rust REST transport generator (TD-126 Phase 4).
//!
//! Mirrors the Go pilot (`clients/go/codegen`, oapi-codegen): emits the typed,
//! low-level REST client (`progenitor::Client` + models) that the hand-written
//! ergonomic facade (`clients/rust/src/client.rs`) calls into. The public Rust
//! SDK API (`proximadb_sdk`) is unchanged when this is regenerated.
//!
//! Invoked by `clients/rust/codegen/gen.sh` (`make gen-rust-sdk`). The
//! progenitor version is pinned in `Cargo.toml`. We use the programmatic
//! `Generator` API (not the `cargo progenitor` CLI) so the output is a single
//! committable module and formatting uses stable `prettyplease` — the
//! `cargo progenitor` CLI shells out to rustfmt with nightly-only options
//! (`wrap_comments`, `normalize_doc_attributes`) which fail on a stable
//! toolchain.
//!
//! Usage: gen <input-3.0.yaml> <output.rs>

use std::process::ExitCode;

use progenitor::{GenerationSettings, Generator, InterfaceStyle, TagStyle};

const GENERATED_HEADER: &str = "\
// @generated by proximadb-genrest-codegen (progenitor) from the published
// OpenAPI spec (docs/openapi/proximadb-openapi.yaml). DO NOT EDIT.
//
// Regenerate with: make gen-rust-sdk
// The CI drift gate `rust-sdk-codegen-drift` regenerates this and
// `git diff --exit-code`s the result, so it cannot silently diverge from the
// published spec. The progenitor version is pinned in
// clients/rust/codegen/Cargo.toml.
#![allow(clippy::all)]
#![allow(dead_code)]
#![allow(unused_imports)]
#![allow(rustdoc::all)]
";

fn run() -> Result<(), String> {
    let args: Vec<String> = std::env::args().collect();
    if args.len() != 3 {
        return Err(format!(
            "usage: {} <input-3.0.yaml> <output.rs>",
            args.first().map(String::as_str).unwrap_or("gen")
        ));
    }
    let input = &args[1];
    let output = &args[2];

    let text = std::fs::read_to_string(input)
        .map_err(|e| format!("failed to read OpenAPI spec at {input}: {e}"))?;
    let spec: openapiv3::OpenAPI = serde_yaml::from_str(&text)
        .map_err(|e| format!("failed to parse OpenAPI YAML at {input}: {e}"))?;

    // Builder interface (matches the Go pilot's ergonomic generated surface):
    // `client.operation_id().arg(..).send().await`. `TagStyle::Merged` keeps a
    // single flat `Client` (no per-tag sub-clients) so the facade calls one
    // type. `with_inner_type` is left default (progenitor owns its reqwest
    // client); the facade configures the reqwest client and passes it in via
    // `Client::new_with_client`.
    let mut settings = GenerationSettings::new();
    settings
        .with_interface(InterfaceStyle::Builder)
        .with_tag(TagStyle::Merged);

    let mut generator = Generator::new(&settings);
    let tokens = generator
        .generate_tokens(&spec)
        .map_err(|e| format!("progenitor code generation failed: {e}"))?;

    // Format with prettyplease (stable; deterministic across patch releases).
    let syntax = syn::parse2::<syn::File>(tokens)
        .map_err(|e| format!("generated tokens failed to parse: {e}"))?;
    let formatted = prettyplease::unparse(&syntax);

    // prettyplease renders multi-line doc comments as `/** ... */` blocks whose
    // inner lines are indented to the block column. rustdoc strips that common
    // indent, but the indented Markdown (e.g. `    let response = ...` example
    // bodies, and prose that rustdoc's CommonMark reader treats as an indented
    // code block) then gets compiled as doctests — a plain `cargo test` fails
    // with parse errors on the prose. Converting the blocks to `///` line-doc
    // comments (content flush against `/// `) removes the indentation ambiguity
    // entirely, and we additionally retag the explicit example fences from
    // `ignore` to `text` so rustdoc never tries to run them. The result is both
    // rustfmt-stable (gen.sh runs `cargo fmt` after this; rustfmt preserves
    // `///` fences and non-Rust `text` fences) and `cargo test`-clean.
    let formatted = normalize_generated_docs(&formatted);

    let body = format!("{GENERATED_HEADER}\n{formatted}");
    std::fs::write(output, body).map_err(|e| format!("failed to write {output}: {e}"))?;
    Ok(())
}

/// Convert prettyplease `/** ... */` doc blocks to `///` line-doc comments and
/// retag ```` ```ignore ```` example fences as ```` ```text ````.
///
/// prettyplease's block shape is: an opening line `<indent>/**<first content>`,
/// zero or more inner lines indented by `<indent>`, and a final line that ends
/// with `*/` (often `<indent>```*/`, i.e. the example fence-close glued to the
/// comment-close). We detect the block by the `/**` opener and end it at the
/// first line ending in `*/`, stripping that suffix. Each resulting content
/// line is emitted as `///` (or bare `///` when empty), flush-left after the
/// indent, which eliminates the indented-code-block ambiguity. Non-doc lines
/// pass through byte-for-byte.
fn normalize_generated_docs(src: &str) -> String {
    let mut out = String::with_capacity(src.len());
    let mut lines = src.lines().peekable();
    while let Some(line) = lines.next() {
        let trimmed = line.trim_start();
        let indent = &line[..line.len() - trimmed.len()];
        let Some(first_rest) = trimmed.strip_prefix("/**") else {
            out.push_str(line);
            out.push('\n');
            continue;
        };
        // Single-line `/** ... */`.
        if let Some(inner) = first_rest.strip_suffix("*/") {
            emit_doc_line(&mut out, indent, inner.trim_end());
            continue;
        }
        emit_doc_line(&mut out, indent, &retag_fence(first_rest));
        for body_line in lines.by_ref() {
            // The block ends at the first line whose trimmed form ends in `*/`.
            if let Some(pre) = body_line.trim_end().strip_suffix("*/") {
                let rel = pre.strip_prefix(indent).unwrap_or(pre);
                let rel = rel.trim_end();
                if !rel.is_empty() {
                    emit_doc_line(&mut out, indent, &retag_fence(rel));
                }
                break;
            }
            let rel = body_line.strip_prefix(indent).unwrap_or(body_line);
            emit_doc_line(&mut out, indent, &retag_fence(rel));
        }
    }
    out
}

/// Swap a lone ```` ```ignore ```` fence opener for ```` ```text ```` so rustdoc
/// never compiles the example. Any other content passes through unchanged.
fn retag_fence(content: &str) -> String {
    if content.trim() == "```ignore" {
        "```text".to_string()
    } else {
        content.to_string()
    }
}

/// Emit one `///`-prefixed doc line. An empty `content` yields a bare `///`.
fn emit_doc_line(out: &mut String, indent: &str, content: &str) {
    out.push_str(indent);
    if content.is_empty() {
        out.push_str("///");
    } else {
        out.push_str("/// ");
        out.push_str(content);
    }
    out.push('\n');
}

fn main() -> ExitCode {
    match run() {
        Ok(()) => ExitCode::SUCCESS,
        Err(e) => {
            eprintln!("error: {e}");
            ExitCode::FAILURE
        }
    }
}
