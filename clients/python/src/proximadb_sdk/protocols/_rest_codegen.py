"""Spec-driven request adapter over the generated REST transport (TD-126 Phase 4).

This is the thin binding layer between the hand-written ergonomic facade
(``rest_sync.py`` / ``rest_async.py``) and the generated low-level REST client in
``proximadb_sdk._generated.rest`` (openapi-python-client output, regenerated by
``make gen-python-sdk`` and drift-gated in CI).

The facade keeps full ownership of ergonomics — client construction, auth,
retries, error mapping, locality-gzip default, response coercion — and continues
to perform every HTTP call through its own ``_make_request`` seam (which the
OpenAPI contract test patches). What it delegates *here* is the part that the
OpenAPI spec actually governs: **the operation's HTTP method, URL template, and
request-body / query-param shape.** Each helper below calls the generated
operation's ``_get_kwargs`` (and, for bodied operations, the generated attrs
request model) so those wire details are derived from the published spec rather
than re-hand-coded in the facade.

Each helper returns a normalized ``RestCall``:
  * ``method``  — upper-cased HTTP verb (the generated client emits lower-case).
  * ``endpoint`` — the resolved URL path (the generated ``url``).
  * ``json``    — request body dict (or ``None``).
  * ``params``  — query params dict (or ``None``).

so the facade can keep calling
``self._make_request(call.method, call.endpoint, json=call.json, params=call.params)``.
"""

from __future__ import annotations

from dataclasses import dataclass
from typing import Any

from .._generated.rest.api.collections import (
    create_collection as _gen_create_collection,
)
from .._generated.rest.api.collections import (
    delete_collection as _gen_delete_collection,
)
from .._generated.rest.api.collections import get_collection as _gen_get_collection
from .._generated.rest.api.collections import list_collections as _gen_list_collections
from .._generated.rest.api.query import execute_query as _gen_execute_query
from .._generated.rest.api.query import explain_query as _gen_explain_query
from .._generated.rest.api.records import get_record as _gen_get_record
from .._generated.rest.api.records import insert_records as _gen_insert_records
from .._generated.rest.api.search import search_records as _gen_search_records
from .._generated.rest.models.create_collection_v2_request import (
    CreateCollectionV2Request,
)
from .._generated.rest.models.explain_query_request import ExplainQueryRequest
from .._generated.rest.models.insert_records_request import InsertRecordsRequest
from .._generated.rest.models.query_request import QueryRequest
from .._generated.rest.models.typed_search_request import TypedSearchRequest
from .._generated.rest.types import UNSET


@dataclass(frozen=True)
class RestCall:
    """Normalized request descriptor produced from a generated operation."""

    method: str
    endpoint: str
    json: Any = None
    params: dict[str, Any] | None = None


def _normalize(kwargs: dict[str, Any]) -> RestCall:
    params = kwargs.get("params") or None
    return RestCall(
        method=str(kwargs["method"]).upper(),
        endpoint=str(kwargs["url"]),
        json=kwargs.get("json"),
        params=params,
    )


def _from_dict(model_cls: Any, body: dict[str, Any]) -> Any:
    """Build a generated attrs request model from a facade-built body dict.

    ``from_dict`` round-trips through the generated model so the body we send is
    exactly the shape the generated client (hence the OpenAPI spec) defines —
    unknown/extra keys are preserved on ``additional_properties`` where the model
    allows them, matching the server's tolerant decoding.
    """
    return model_cls.from_dict(body)


# ---------------------------------------------------------------------------
# Collections
# ---------------------------------------------------------------------------


def create_collection(body: dict[str, Any]) -> RestCall:
    model = _from_dict(CreateCollectionV2Request, body)
    return _normalize(_gen_create_collection._get_kwargs(body=model))


def get_collection(collection_id: str) -> RestCall:
    return _normalize(_gen_get_collection._get_kwargs(collection_id))


def delete_collection(collection_id: str) -> RestCall:
    return _normalize(_gen_delete_collection._get_kwargs(collection_id))


def list_collections(
    *,
    limit: int | None = None,
    offset: int | None = None,
    include_stats: bool | None = None,
) -> RestCall:
    return _normalize(
        _gen_list_collections._get_kwargs(
            limit=UNSET if limit is None else limit,
            offset=UNSET if offset is None else offset,
            include_stats=UNSET if include_stats is None else include_stats,
        )
    )


# ---------------------------------------------------------------------------
# Records
# ---------------------------------------------------------------------------


def insert_records(collection_id: str, body: dict[str, Any]) -> RestCall:
    model = _from_dict(InsertRecordsRequest, body)
    return _normalize(
        _gen_insert_records._get_kwargs(collection_id=collection_id, body=model)
    )


def get_record(
    collection_id: str,
    record_id: str,
    *,
    include_vector: bool | None = None,
    include_text: bool | None = None,
) -> RestCall:
    return _normalize(
        _gen_get_record._get_kwargs(
            collection_id=collection_id,
            record_id=record_id,
            include_vector=UNSET if include_vector is None else include_vector,
            include_text=UNSET if include_text is None else include_text,
        )
    )


# ---------------------------------------------------------------------------
# Search / Query
# ---------------------------------------------------------------------------


def search_records(collection_id: str, body: dict[str, Any]) -> RestCall:
    model = _from_dict(TypedSearchRequest, body)
    return _normalize(
        _gen_search_records._get_kwargs(collection_id=collection_id, body=model)
    )


def _path_only(get_kwargs: Any, body: dict[str, Any], model_cls: Any) -> RestCall:
    """Source method+URL from the generated operation, send the raw body.

    Used for the AQL/UQL/federated query operations. Their OpenAPI
    ``parameters`` field is typed as an array of *objects*, but the facade's
    public API accepts positional scalar bind values (e.g. ``[1, "x"]``), which
    the server decodes leniently. Round-tripping those scalars through the
    generated attrs model would reject them, so we bind the spec-governed
    method+URL from the generated endpoint while preserving the facade's body
    verbatim. ``model_cls`` is referenced only to keep the spec linkage explicit.
    """
    assert model_cls is not None
    call = _normalize(get_kwargs(body=_EMPTY_BODY_SENTINEL))
    return RestCall(method=call.method, endpoint=call.endpoint, json=body)


class _EmptyBody:
    """Minimal stand-in so the generated _get_kwargs can build method+URL.

    ``_get_kwargs`` calls ``body.to_dict()``; we only need the method/url it
    returns, so a no-op ``to_dict`` is sufficient and the result is discarded.
    """

    @staticmethod
    def to_dict() -> dict[str, Any]:
        return {}


_EMPTY_BODY_SENTINEL = _EmptyBody()


def execute_query(body: dict[str, Any]) -> RestCall:
    return _path_only(_gen_execute_query._get_kwargs, body, QueryRequest)


def explain_query(body: dict[str, Any]) -> RestCall:
    return _path_only(_gen_explain_query._get_kwargs, body, ExplainQueryRequest)
